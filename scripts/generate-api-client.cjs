const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const contractPath = path.join(root, 'packages/api-client/openapi.json');
const destination = path.join(root, 'packages/api-client/generated/models.ts');
const contract = JSON.parse(fs.readFileSync(contractPath, 'utf8'));
if (contract.openapi !== '3.1.0') throw new Error('Expected OpenAPI 3.1.0');
const schemas = contract.components.schemas;
const reference = ref => {
  const prefix = '#/components/schemas/';
  if (!ref.startsWith(prefix) || !Object.hasOwn(schemas, ref.slice(prefix.length))) throw new Error('Unsupported schema reference: ' + ref);
  return ref.slice(prefix.length);
};
function typeOf(schema) {
  if (schema === true) return 'unknown';
  if (schema === false) return 'never';
  if (schema.$ref) return reference(schema.$ref);
  if (Object.hasOwn(schema, 'const')) return JSON.stringify(schema.const);
  if (schema.enum) return schema.enum.map(value => JSON.stringify(value)).join(' | ');
  for (const keyword of ['anyOf', 'oneOf', 'allOf']) {
    if (schema[keyword]) return '(' + schema[keyword].map(typeOf).join(keyword === 'allOf' ? ' & ' : ' | ') + ')';
  }
  if (Array.isArray(schema.type)) return '(' + schema.type.map(type => typeOf({ ...schema, type })).join(' | ') + ')';
  switch (schema.type) {
    case 'null': return 'null';
    case 'string': return 'string';
    case 'integer': case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'array': return 'Array<' + typeOf(schema.items ?? true) + '>';
    case 'object': {
      const required = new Set(schema.required ?? []);
      const fields = Object.entries(schema.properties ?? {}).map(([key, value]) => `  ${JSON.stringify(key)}${required.has(key) ? '' : '?'}: ${typeOf(value)};`);
      // Preserve explicitly declared dictionary semantics without widening known fields.
      if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
        const dictionary = `Record<string, ${typeOf(schema.additionalProperties)}>`;
        return fields.length ? `({\n${fields.join('\n')}\n} & ${dictionary})` : dictionary;
      }
      return `{\n${fields.join('\n')}\n}`;
    }
    default:
      if (Object.keys(schema).every(key => ['description', 'title', 'default', 'examples'].includes(key))) return 'unknown';
      throw new Error('Unsupported schema: ' + JSON.stringify(schema));
  }
}
const operations = {};
for (const [route, methods] of Object.entries(contract.paths)) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!['get', 'post', 'patch', 'delete', 'put'].includes(method)) continue;
    if (!operation.operationId || Object.hasOwn(operations, operation.operationId)) throw new Error('Missing or repeated operation ID');
    const success = Object.entries(operation.responses).filter(([status]) => /^2\d\d$/.test(status));
    if (success.length !== 1) throw new Error('Expected one typed success response per operation');
    const [status, response] = success[0];
    const responseSchema = reference(response.content['application/json'].schema.$ref);
    operations[operation.operationId] = { method: method.toUpperCase(), path: route, status: Number(status), responseSchema };
  }
}
const hash = crypto.createHash('sha256').update(JSON.stringify(contract)).digest('hex');
const output = '// Generated by npm run api:generate. Do not edit.\n'
  + `// OpenAPI SHA-256: ${hash}\n\n`
  + Object.entries(schemas).map(([name, schema]) => {
    if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)) throw new Error('Invalid schema name');
    return `export type ${name} = ${typeOf(schema)};\n`;
  }).join('\n')
  + `\nexport const operations = ${JSON.stringify(operations, null, 2)} as const;\n`;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) throw new Error('Generated API client is out of date. Run npm run api:generate.');
} else {
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, output, 'utf8');
}
